def chain(node, number, title, names, ins, ctrls, outs, links, mechs, fname, extra=None):
    """Декомпозиция второго уровня: блоки «лестницей».
    ins: [(box, frac, label)], ctrls: [(box, frac, label)], outs: [(box, frac, label)],
    links: [(src, sfrac, dst, side, dfrac, label)] side in 'L','T'; mechs: [(box, frac, label)]"""
    d = Diagram(title=title, node=node, number=number)
    n = len(names)
    W, H = 2.05, 1.32
    x0, x1 = 1.9, 11.0 if n == 5 else 10.6
    y0, y1 = 8.0, 2.3
    for i, nm in enumerate(names):
        x = x0 + (x1 - x0) * i / (n - 1)
        y = y0 + (y1 - y0) * i / (n - 1)
        d.box(f"{node}{i+1}", x, y, W, H, nm, f"{node}{i+1}", fs=10.5, wrapw=17)
    K = lambda i: f"{node}{i}"
    for b, f, t, *o in ins:
        p = d.L(K(b), f)
        kw = dict(lpos=(d.left + 0.1, p[1] + 0.06), wrapw=11)
        if o:  # индивидуальное положение подписи, чтобы подписи соседних стрелок не накладывались
            dy = o[0].pop("dy", 0.06)
            kw.update(lpos=(d.left + 0.1, p[1] + dy), **o[0])
        d.arrow([(d.left, p[1]), p], t, **kw)
    for b, f, t, *o in ctrls:
        p = d.T(K(b), f)
        kw = dict(lpos=(p[0] + 0.08, d.top - 0.3), wrapw=14, lva="top")
        if o:
            kw.update(o[0])
        d.arrow([(p[0], d.top - 0.2), p], t, **kw)
    for b, f, t in outs:
        p = d.R(K(b), f)
        d.arrow([p, (d.right, p[1])], t, lpos=(max(p[0] + 0.12, d.right - 2.6), p[1] + 0.06), wrapw=18)
    for s, sf, t, side, tf, lab in links:
        a = d.R(K(s), sf)
        if side == "L":
            l = d.L(K(t), tf)
            xm = a[0] + 0.16
            if t == s + 1:
                d.arrow([a, (xm, a[1]), (xm, l[1]), l], lab, lpos=(xm - 0.08, (a[1] + l[1]) / 2), lal="right", lva="center", wrapw=13)
            else:
                xm = d.L(K(t), 0)[0] - 0.25
                d.arrow([a, (xm, a[1]), (xm, l[1]), l], lab, lpos=(a[0] + 0.12, a[1] + 0.06), wrapw=40)
        else:
            tp = d.T(K(t), tf)
            d.arrow([a, (tp[0], a[1]), tp], lab, lpos=(a[0] + 0.12, a[1] + 0.06), wrapw=40)
    for b, f, t in mechs:
        p = d.B(K(b), f)
        d.arrow([(p[0], d.bottom + 0.05), p], t, lpos=(p[0] + 0.08, d.bottom + 0.15), wrapw=13)
    if extra:
        extra(d)
    d.save(f"{OUT}/{fname}")


